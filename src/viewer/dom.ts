export function icon(name: keyof typeof PATHS | string, size = 16): SVGSVGElement {
  const t = document.createElement("template");
  t.innerHTML = `<svg class="icon" xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">${PATHS[name] ?? ""}</svg>`;
  return t.content.firstElementChild as SVGSVGElement;
}

