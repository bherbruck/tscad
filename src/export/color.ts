/** RGBA, each 0–255. */
export type Rgba = [number, number, number, number];

/** The colour used when a part has none (or an unparseable one). */
export const DEFAULT_COLOR: Rgba = [0xb0, 0xb8, 0xc4, 255];

const clamp = (v: number) => Math.max(0, Math.min(255, Math.round(v)));

function channel(s: string, max: number): number {
  s = s.trim();
  return s.endsWith("%") ? (parseFloat(s) / 100) * max : parseFloat(s);
}

function hsl(h: number, s: number, l: number): [number, number, number] {
  const k = (n: number) => (n + h / 30) % 12;
  const a = s * Math.min(l, 1 - l);
  const f = (n: number) => l - a * Math.max(-1, Math.min(k(n) - 3, 9 - k(n), 1));
  return [f(0) * 255, f(8) * 255, f(4) * 255];
}

/** Parse a CSS colour (`#rgb`, `#rgba`, `#rrggbb`, `#rrggbbaa`, `rgb()/rgba()`, `hsl()/hsla()`, names). */
export function parseColor(input: string | undefined): Rgba | undefined {
  if (!input) return undefined;
  const s = input.trim().toLowerCase();
  if (s.startsWith("#")) {
    let h = s.slice(1);
    if (!/^[0-9a-f]+$/.test(h)) return undefined;
    if (h.length === 3 || h.length === 4) h = [...h].map((c) => c + c).join("");
    if (h.length !== 6 && h.length !== 8) return undefined;
    const n = (i: number) => parseInt(h.slice(i, i + 2), 16);
    return [n(0), n(2), n(4), h.length === 8 ? n(6) : 255];
  }
  const fn = /^(rgba?|hsla?)\(([^)]*)\)$/.exec(s);
  if (fn) {
    const parts = fn[2]!.split(/[\s,/]+/).filter(Boolean);
    if (parts.length < 3) return undefined;
    const alpha = parts[3] !== undefined ? clamp(channel(parts[3], 1) * 255) : 255;
    if (fn[1]!.startsWith("rgb")) {
      const [r, g, b] = parts.slice(0, 3).map((p) => clamp(channel(p, 255)));
      if ([r, g, b].some((v) => Number.isNaN(v))) return undefined;
      return [r!, g!, b!, alpha];
    }
    const [r, g, b] = hsl(parseFloat(parts[0]!), channel(parts[1]!, 1), channel(parts[2]!, 1));
    return [clamp(r), clamp(g), clamp(b), alpha];
  }
  if (s === "transparent") return [0, 0, 0, 0];
  const named = NAMED[s];
  return named === undefined ? undefined : [(named >> 16) & 255, (named >> 8) & 255, named & 255, 255];
}

/** `#RRGGBB` (or `#RRGGBBAA` when not opaque), upper case, as 3MF wants. */
export function toHex(c: Rgba): string {
  const hex = (v: number) => v.toString(16).padStart(2, "0").toUpperCase();
  return `#${hex(c[0])}${hex(c[1])}${hex(c[2])}${c[3] === 255 ? "" : hex(c[3])}`;
}

/** sRGB byte → linear float, for glTF `baseColorFactor`. */
export function srgbToLinear(v: number): number {
  const c = v / 255;
  return c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
}
