/**
 * Regenerates src/core/text/default-font.ts (base64 of DejaVuSans-subset.ttf), so the default
 * font loads synchronously in bun and in browser bundles with no fetch.
 *   bun assets/fonts/embed.ts
 * The subset was made with: pyftsubset DejaVuSans.ttf --unicodes="U+0020-007E,U+00A0-00FF,..."
 *   --layout-features="kern,liga" --no-hinting --desubroutinize
 */
const ttf = await Bun.file(new URL("./DejaVuSans-subset.ttf", import.meta.url)).bytes();
const b64 = Buffer.from(ttf).toString("base64");
const out = `// Generated by assets/fonts/embed.ts — do not edit.
// DejaVu Sans (subset). Bitstream Vera license: assets/fonts/LICENSE-DejaVu.txt
/** The default \`<text>\` font, base64 TTF. */
export const DEFAULT_FONT_BASE64 =
  ${JSON.stringify(b64)};
`;
await Bun.write(new URL("../../src/core/text/default-font.ts", import.meta.url), out);
console.log(`wrote ${b64.length} base64 chars`);
